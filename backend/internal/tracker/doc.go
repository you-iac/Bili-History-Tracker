// Package tracker 实现后台的循环查询：按调度表逐个查询作者资料和视频元数据，
// 把成功观测交给 storage 落库，并把每次查询的结果写入内存环形日志和日志文件。
//
// 输入：storage.Target（类型、ID、间隔；平台名当前由构造函数提供），以及
// Querier 接口返回的上游数据。
// 输出：以副作用为主——storage 落库、记录指标、推进调度表，Log 写日志；
// RunTarget / RunNow 不向调用方返回结果，失败只体现在日志里。
// RequestTarget 为 Agent 验证并接纳新目标，已跟踪目标不重复采集或改调度；见 docs/client-library.md。
// 它不认识：B站 HTTP 细节、SQL 语句、HTML 页面。
//
// 上下游关系：
//
//	┌────────────────────────────┐                                  ┌────────────────────────────┐
//	│ admin                      │                                  │ scheduler.go               │
//	│ RunNow：立即查询           │                                  │ 到期检查 / RunTarget       │──────────┐
//	└────────────────────────────┘                                  └────────────────────────────┘          │
//	               │                                                               │                        │
//	 异步触发      │                                                 循环调度      │                        │
//	               └───────────────────────────────┬───────────────────────────────┘                        │
//	                                               ▼                                                        │
//	                                ┌────────────────────────────┐                                          │
//	                                │ tracker.go                 │                                          │
//	                                │ 去重 / 单次查询 / 入库     │──────────────────────────────────────┐   │
//	                                └────────────────────────────┘                                      │   │
//	                                               │                                                    │   │
//	 取数 / 发现                                   │                 计算 / 写入                        │   │
//	               ┌───────────────────────────────┴───────────────────────────────┐                    │   │
//	               ▼                                                               ▼                    │   │
//	┌────────────────────────────┐                                  ┌────────────────────────────┐      │   │
//	│ source.Service             │                                  │ storage                    │      │   │
//	│ 视频 / 作者 / 视频续页     │                                  │ 指纹 / 保存 / 指标 / 目标  │◄─────┼───┘
//	└────────────────────────────┘                                  └────────────────────────────┘      │
//	                                                                 调度器读写到期时间                 │
//	                                                                                                    │
//	                                                                                                    │
//	                                                                                                    │
//	                                ┌────────────────────────────┐                                      │
//	                                │ log.go                     │       记录查询结果                   │
//	                                │ 内存日志 / query.log       │◄─────────────────────────────────────┘
//	                                └────────────────────────────┘
//
// 本包不做状态推断：查询失败只记录错误，不删除或降级已有内容。
// 调度串行执行；作者视频发现由 discovery 显式请求，本包仅按平台透传能力。
// 作者资料采集与视频关注独立；显式导入与定时查询共用保存链路。
// 新增链路见 docs/video-discovery.md。
