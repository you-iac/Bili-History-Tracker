// Package admin 提供 8182 端口的本地后台：查看跟踪目标、查询日志和入库详情，
// 并允许添加、删除、立即查询目标和调整查询间隔。
// Agent 复用同路径 JSON 读取和验证后目标提交；仍沿用可信管理服务部署，见 docs/client-library.md。
// 作者视频经 discovery 提供统一发现、分页及显式导入；列表不写内容或关注，
// 添加全部和逐项选择共用写入用例。设计见 docs/video-discovery.md。
//
// 输入：浏览器提交的表单（type、id、interval_hours）和 URL 参数。
// 输出：HTML 页面；副作用是写 tracking_targets、触发 tracker.RunNow、
// 读取 storage 的详情和统计。
// 它不认识：B站端点、指纹算法、调度器内部循环；自身不直接请求上游，
// 触发的 RunNow 由 tracker 异步执行。
//
// 上下游关系：
//
//	                                  ┌────────────────────────────┐
//	                                  │ 浏览器                     │
//	                                  │ GET 页面 / POST 表单       │
//	                                  └────────────────────────────┘
//	                                                 │
//	                                                 │ HTTP
//	                                                 │
//	                                                 ▼
//	                                  ┌────────────────────────────┐
//	                                  │ server.go                  │
//	                                ┌─│ 路由 / 校验 / 调用 / 渲染  │
//	                                │ └────────────────────────────┘
//	                                │                │
//	 读取 / 修改                    │                │                    渲染 HTML
//	               ┌────────────────┼────────────────┼─────────────────────────────────┐
//	               ▼                │                │                                 ▼
//	┌────────────────────────────┐  │                │                  ┌────────────────────────────┐
//	│ storage                    │  │                │                  │ templates/*.html           │
//	│ 目标读写 / 详情 / 统计     │  │                │                  │ go:embed 服务端模板        │
//	└────────────────────────────┘  │                │                  └────────────────────────────┘
//	                                │                │ 触发查询
//	 读取日志                       │                │
//	               ┌────────────────┘                │
//	               ▼                                 ▼
//	┌────────────────────────────┐    ┌────────────────────────────┐
//	│ tracker.Log                │    │ tracker.RunNow             │
//	│ 读取最近查询日志           │    │ 异步执行单个跟踪目标       │
//	└────────────────────────────┘    └────────────────────────────┘
//
// 后台不设登录与权限，默认只监听回环地址；它直接调用 storage 和 tracker，
// 不经过对外查询 API。
